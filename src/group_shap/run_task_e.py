"""
Task E - Group SHAP analysis for the ISCX VPN/Non-VPN dataset.

Uses the SHAP values already generated by Task C.
No model retraining and no changes to datasets or existing C outputs.

For each context/model:
1. Load C's raw SHAP values with shape (classes, samples, features).
2. Compute mean absolute SHAP per feature.
3. Aggregate features into the predefined semantic families.
4. Compute normalized group contribution.
5. Rank feature families.
6. Compare VPN vs Non-VPN group rankings.
"""

from pathlib import Path
import json

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, kendalltau


ROOT = Path(__file__).resolve().parents[2]

SHAP_RESULTS_DIR = ROOT / "SHAP" / "results"
OUTPUT_DIR = ROOT / "results" / "group_shap"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

FEATURES = [
    "duration",
    "total_fiat",
    "total_biat",
    "min_fiat",
    "min_biat",
    "max_fiat",
    "max_biat",
    "mean_fiat",
    "mean_biat",
    "flowPktsPerSecond",
    "flowBytesPerSecond",
    "min_flowiat",
    "max_flowiat",
    "mean_flowiat",
    "std_flowiat",
    "min_active",
    "mean_active",
    "max_active",
    "std_active",
    "min_idle",
    "mean_idle",
    "max_idle",
    "std_idle",
]

GROUPS = {
    "Flow duration": [
        "duration",
    ],
    "Directional IAT statistics": [
        "total_fiat",
        "total_biat",
        "min_fiat",
        "min_biat",
        "max_fiat",
        "max_biat",
        "mean_fiat",
        "mean_biat",
    ],
    "Flow throughput": [
        "flowPktsPerSecond",
        "flowBytesPerSecond",
    ],
    "Flow IAT statistics": [
        "min_flowiat",
        "max_flowiat",
        "mean_flowiat",
        "std_flowiat",
    ],
    "Active-period statistics": [
        "min_active",
        "mean_active",
        "max_active",
        "std_active",
    ],
    "Idle-period statistics": [
        "min_idle",
        "mean_idle",
        "max_idle",
        "std_idle",
    ],
}

CONTEXTS = ("novpn", "vpn")
MODELS = ("RandomForest", "XGBoost")


def validate_groups():
    flattened = [
        feature
        for members in GROUPS.values()
        for feature in members
    ]

    if len(flattened) != len(FEATURES):
        raise ValueError(
            f"Expected {len(FEATURES)} grouped features, "
            f"got {len(flattened)}."
        )

    if set(flattened) != set(FEATURES):
        missing = sorted(set(FEATURES) - set(flattened))
        extra = sorted(set(flattened) - set(FEATURES))

        raise ValueError(
            f"Feature-family mismatch. Missing={missing}, extra={extra}"
        )

    if len(flattened) != len(set(flattened)):
        raise ValueError("A feature appears in more than one family.")


def load_shap_values(context, model_name):
    path = (
        SHAP_RESULTS_DIR
        / f"shap_values_{context}_{model_name}.npy"
    )

    if not path.exists():
        raise FileNotFoundError(
            f"Missing Task C SHAP file: {path}"
        )

    sv = np.load(path)

    if sv.ndim != 3:
        raise ValueError(
            f"{path.name}: expected 3D SHAP array, got {sv.shape}"
        )

    n_classes, n_samples, n_features = sv.shape

    if n_classes != 7:
        raise ValueError(
            f"{path.name}: expected 7 classes, got {n_classes}"
        )

    if n_features != len(FEATURES):
        raise ValueError(
            f"{path.name}: expected {len(FEATURES)} features, "
            f"got {n_features}"
        )

    return sv


def calculate_group_table(sv):
    mean_abs_feature = np.mean(
        np.abs(sv),
        axis=(0, 1),
    )

    feature_importance = pd.Series(
        mean_abs_feature,
        index=FEATURES,
        dtype=float,
    )

    rows = []

    for group_name, members in GROUPS.items():
        attribution = float(
            feature_importance.loc[members].sum()
        )

        rows.append({
            "group": group_name,
            "n_features": len(members),
            "group_mean_abs_shap": attribution,
        })

    table = pd.DataFrame(rows)

    total = table["group_mean_abs_shap"].sum()

    if total <= 0:
        raise ValueError(
            "Total group SHAP attribution is not positive."
        )

    table["normalized_contribution"] = (
        table["group_mean_abs_shap"] / total
    )

    table = table.sort_values(
        "normalized_contribution",
        ascending=False,
    ).reset_index(drop=True)

    table["rank"] = np.arange(
        1,
        len(table) + 1,
    )

    return table


def compare_group_rankings(novpn_table, vpn_table):
    novpn_ranks = (
        novpn_table
        .set_index("group")["rank"]
        .reindex(GROUPS.keys())
    )

    vpn_ranks = (
        vpn_table
        .set_index("group")["rank"]
        .reindex(GROUPS.keys())
    )

    rho, p_rho = spearmanr(
        novpn_ranks.values,
        vpn_ranks.values,
    )

    tau, p_tau = kendalltau(
        novpn_ranks.values,
        vpn_ranks.values,
    )

    comparison = pd.DataFrame({
        "group": list(GROUPS.keys()),
        "non_vpn_rank": novpn_ranks.values.astype(int),
        "vpn_rank": vpn_ranks.values.astype(int),
    })

    comparison["abs_rank_shift"] = (
        comparison["non_vpn_rank"] -
        comparison["vpn_rank"]
    ).abs()

    return {
        "spearman_rho": float(rho),
        "spearman_p": float(p_rho),
        "kendall_tau": float(tau),
        "kendall_p": float(p_tau),
        "mean_abs_rank_displacement": float(
            comparison["abs_rank_shift"].mean()
        ),
        "rank_comparison": comparison,
    }


def main():
    validate_groups()

    all_group_rows = []
    rankings = {}

    print("=== Task E: Group SHAP Analysis ===")

    for context in CONTEXTS:
        for model_name in MODELS:
            sv = load_shap_values(
                context,
                model_name,
            )

            table = calculate_group_table(sv)

            rankings[(context, model_name)] = table

            output_path = (
                OUTPUT_DIR
                / f"group_shap_{context}_{model_name}.csv"
            )

            table.to_csv(
                output_path,
                index=False,
            )

            for _, row in table.iterrows():
                all_group_rows.append({
                    "context": context,
                    "model": model_name,
                    **row.to_dict(),
                })

            print(
                f"\n{context.upper()} - {model_name}"
            )

            for _, row in table.iterrows():
                print(
                    f"{int(row['rank']):d}. "
                    f"{row['group']}: "
                    f"{row['normalized_contribution']:.4f}"
                )

    combined = pd.DataFrame(all_group_rows)

    combined.to_csv(
        OUTPUT_DIR / "group_shap_all_results.csv",
        index=False,
    )

    comparison_rows = []

    for model_name in MODELS:
        novpn_table = rankings[
            ("novpn", model_name)
        ]

        vpn_table = rankings[
            ("vpn", model_name)
        ]

        result = compare_group_rankings(
            novpn_table,
            vpn_table,
        )

        rank_comparison = result.pop(
            "rank_comparison"
        )

        rank_comparison.insert(
            0,
            "model",
            model_name,
        )

        rank_comparison["non_vpn_contribution"] = (
            rank_comparison["group"]
            .map(
                novpn_table.set_index("group")[
                    "normalized_contribution"
                ]
            )
        )

        rank_comparison["vpn_contribution"] = (
            rank_comparison["group"]
            .map(
                vpn_table.set_index("group")[
                    "normalized_contribution"
                ]
            )
        )

        rank_comparison["absolute_contribution_change"] = (
            rank_comparison["vpn_contribution"] -
            rank_comparison["non_vpn_contribution"]
        ).abs()

        rank_comparison.to_csv(
            OUTPUT_DIR
            / f"group_ranking_comparison_{model_name}.csv",
            index=False,
        )

        comparison_rows.append({
            "model": model_name,
            "spearman_rho": result["spearman_rho"],
            "spearman_p": result["spearman_p"],
            "kendall_tau": result["kendall_tau"],
            "kendall_p": result["kendall_p"],
            "mean_abs_rank_displacement":
                result["mean_abs_rank_displacement"],
        })

    comparison_summary = pd.DataFrame(
        comparison_rows
    )

    comparison_summary.to_csv(
        OUTPUT_DIR
        / "group_cross_context_summary.csv",
        index=False,
    )

    with open(
        OUTPUT_DIR / "feature_group_definitions.json",
        "w",
        encoding="utf-8",
    ) as f:
        json.dump(
            GROUPS,
            f,
            indent=2,
        )

    print(
        "\nTask E completed."
        f"\nOutputs written to: {OUTPUT_DIR}"
    )


if __name__ == "__main__":
    main()
